#!/usr/bin/env python3
"""Build bench/MODEL_RESULTS.md: one row per model, from every results.jsonl under
bench/results/handoff/.

    python bench/harness/leaderboard.py [--hops 1]

Verdicts, per model, for the Pith-with-skill arm against English:
  can't take the test   oracle below 90%: the model cannot answer even with the full notes
  holds accuracy        paired accuracy difference of -2 points or better
  loses accuracy        worse than -2 points and the 95% interval is entirely below zero
  unclear               anything else (the interval is too wide to call)
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)

from report import boot_ci, load, mean  # noqa: E402
from suite_handoff import QUESTION_NAMES  # noqa: E402

RESULTS = os.path.join(ROOT, "bench", "results", "handoff")
ARMS = ["english", "terse", "json", "pith_skill", "pith_primer"]
V11 = ["pith_skill_1.1", "pith_primer_1.1"]
MIN_CASES = 10  # a model with fewer finished cases is too noisy to list


def paired(by_arm, base, arm, key):
    pairs = [(by_arm[base][c], by_arm[arm][c]) for c in by_arm.get(arm, {})
             if c in by_arm.get(base, {}) and by_arm[base][c]["status"] == "ok"
             and by_arm[arm][c]["status"] == "ok"]
    return pairs


def verdict(oracle, d, lo, hi):
    if oracle < 0.90:
        return "can't take the test"
    if d >= -0.02:
        return "holds accuracy"
    if hi < 0:
        return "loses accuracy"
    return "unclear"


def summarise(path, hops, cases="original"):
    rows, errors = load(path, hops, cases)
    if not rows:
        return None
    by_arm = {}
    for r in rows:
        by_arm.setdefault(r["arm"], {})[r["case"]] = r

    def acc(arm):
        ok = [r["grade"]["acc"] for r in by_arm.get(arm, {}).values() if r["status"] == "ok"]
        return mean(ok) if ok else float("nan")

    def msg(arm):
        ok = [r["msg_tokens"] for r in by_arm.get(arm, {}).values() if r["status"] == "ok" and r["msg_tokens"]]
        return mean(ok) if ok else float("nan")

    wrong = {}
    for arm in ("english", "terse", "pith_skill"):
        for r in by_arm.get(arm, {}).values():
            if r["status"] != "ok":
                continue
            for q in r["per_q"]:
                key = (r["kind"], int(q["id"][1:]) - 1)
                wrong.setdefault(key, {}).setdefault(arm, [0, 0])
                wrong[key][arm][0] += 0 if q["ok"] else 1
                wrong[key][arm][1] += 1
    s = {"model": rows[0]["model"], "wrong": wrong, "cases": len(by_arm.get("english", {})), "errors": errors,
         "oracle": acc("oracle"), "null": acc("null"),
         "acc": {a: acc(a) for a in ARMS + V11}, "msg": {a: msg(a) for a in ARMS + V11}}
    for arm in ("pith_skill", "pith_primer") + tuple(V11):
        pairs = paired(by_arm, "english", arm, "acc")
        if pairs:
            d = [y["grade"]["acc"] - x["grade"]["acc"] for x, y in pairs]
            lo, hi = boot_ci(d)
            s[arm] = {"d": mean(d), "lo": lo, "hi": hi,
                      "verdict": verdict(s["oracle"], mean(d), lo, hi),
                      "status": mean([y["grade"].get("acc_status", 0) - x["grade"].get("acc_status", 0)
                                      for x, y in pairs])}
        ok = [r for r in by_arm.get(arm, {}).values() if r["status"] == "ok"]
        if ok:
            s[arm + "_lint"] = sum(1 for r in ok if r.get("lint_errors") == 0) / len(ok)
    return s


def f(x, digits=1):
    return "-" if x != x else f"{x * 100:.{digits}f}"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser()
    p.add_argument("--hops", type=int, default=1)
    args = p.parse_args()
    models, heldout = [], []
    for name in sorted(os.listdir(RESULTS)):
        path = os.path.join(RESULTS, name)
        if os.path.isfile(os.path.join(path, "results.jsonl")):
            s = summarise(path, args.hops)
            if s and s["cases"] >= MIN_CASES:
                models.append(s)
            h = summarise(path, args.hops, "heldout")
            if h and h["cases"] >= MIN_CASES:
                heldout.append(h)
    models.sort(key=lambda s: -s["oracle"])
    heldout.sort(key=lambda s: -s["oracle"])

    out = ["# Pith benchmark results", "",
           "Suite A, handoff accuracy: a sender agent writes one message in the format under test; a "
           "fresh reader agent answers 11 multiple-choice questions about it, graded against the "
           "sender's notes by code. Sender and reader are the same model, with greedy decoding and "
           "thinking off. Local models ran in LM Studio (Q4 GGUF) on an RTX 3070 8 GB; hosted models "
           "ran through their provider's API. Method and how to reproduce: "
           "[HOW_TO_TEST.md](HOW_TO_TEST.md). Generated by `python bench/harness/leaderboard.py`.", "",
           "Two case sets: the **original** cases (seed 2026), on which Pith 1.0 was tested and its "
           "failures studied, and **held-out** cases (other seeds), generated after Pith 1.1 was "
           "written, so 1.1 was not tuned on them.", "",
           "## Does Pith work on this model?", "",
           "Accuracy difference is Pith-with-skill minus plain English on the same cases, in points, "
           "with a 95% interval. A model can only be judged if it scores at least 90% when handed the "
           "full notes (oracle).", "",
           "| model | cases | oracle | null | Pith vs English (points) | verdict | evidence-status diff | Pith msg tokens vs English | Pith lint-clean |",
           "|---|---:|---:|---:|---|---|---:|---:|---:|"]
    for s in models:
        ps = s.get("pith_skill")
        if not ps:
            continue
        tok = (s["msg"]["pith_skill"] / s["msg"]["english"] - 1) if s["msg"]["english"] else float("nan")
        out.append(f"| {s['model']} | {s['cases']} | {f(s['oracle'])} | {f(s['null'])} | "
                   f"{ps['d'] * 100:+.1f} ({ps['lo'] * 100:+.1f} to {ps['hi'] * 100:+.1f}) | "
                   f"**{ps['verdict']}** | {ps['status'] * 100:+.1f} | {tok * 100:+.0f}% | "
                   f"{f(s.get('pith_skill_lint', float('nan')), 0)}% |")

    out += ["", "## Accuracy by format (%)", "",
            "| model | english | terse | json | pith (skill) | pith (primer only) |",
            "|---|---:|---:|---:|---:|---:|"]
    for s in models:
        out.append(f"| {s['model']} | " + " | ".join(f(s["acc"][a]) for a in ARMS) + " |")

    out += ["", "## Message length by format (tokens, the model's own tokenizer)", "",
            "| model | english | terse | json | pith (skill) | pith (primer only) |",
            "|---|---:|---:|---:|---:|---:|"]
    for s in models:
        out.append(f"| {s['model']} | " + " | ".join("-" if s["msg"][a] != s["msg"][a] else f"{s['msg'][a]:.0f}"
                                                   for a in ARMS) + " |")

    out += ["", "## Pith 1.0 with only its 103-token primer", "",
            "| model | Pith-primer vs English (points) | verdict | lint-clean |", "|---|---|---|---:|"]
    for s in models:
        pp = s.get("pith_primer")
        if pp:
            out.append(f"| {s['model']} | {pp['d'] * 100:+.1f} ({pp['lo'] * 100:+.1f} to {pp['hi'] * 100:+.1f}) "
                       f"| {pp['verdict']} | {f(s.get('pith_primer_lint', float('nan')), 0)}% |")

    if heldout:
        out += ["", "## Held-out cases: Pith 1.0 vs Pith 1.1", "",
                "Same models, new cases. Differences are against plain English on the same cases, in points, "
                "with a 95% interval.", "",
                "| model | cases | oracle | english | terse | Pith 1.0 | Pith 1.1 | Pith 1.1 vs English | verdict | Pith 1.1 primer only | Pith 1.1 msg tokens vs English |",
                "|---|---:|---:|---:|---:|---:|---:|---|---|---:|---:|"]
        for s in heldout:
            p11 = s.get("pith_skill_1.1")
            if not p11:
                continue
            tok = (s["msg"]["pith_skill_1.1"] / s["msg"]["english"] - 1) if s["msg"]["english"] else float("nan")
            out.append(f"| {s['model']} | {s['cases']} | {f(s['oracle'])} | {f(s['acc']['english'])} | "
                       f"{f(s['acc']['terse'])} | {f(s['acc']['pith_skill'])} | {f(s['acc']['pith_skill_1.1'])} | "
                       f"{p11['d'] * 100:+.1f} ({p11['lo'] * 100:+.1f} to {p11['hi'] * 100:+.1f}) | "
                       f"**{p11['verdict']}** | {f(s['acc']['pith_primer_1.1'])} | {tok * 100:+.0f}% |")

    judged = [s for s in models if s["oracle"] >= 0.90]
    if judged:
        out += ["", "## Where Pith gains and loses", "",
                f"Error rate per question, pooled over the {len(judged)} models that pass the oracle check "
                "(" + ", ".join(s["model"] for s in judged) + "). Sorted by Pith minus English: the top rows "
                "are where Pith helps the reader, the bottom rows where it hurts.", "",
                "| handoff | question | English wrong | terse wrong | Pith wrong | Pith minus English |",
                "|---|---|---:|---:|---:|---:|"]
        table = []
        for kind, names in QUESTION_NAMES.items():
            for i, name in enumerate(names):
                tot = {a: [0, 0] for a in ("english", "terse", "pith_skill")}
                for s in judged:
                    for a, (w, n) in s["wrong"].get((kind, i), {}).items():
                        tot[a][0] += w
                        tot[a][1] += n
                rate = {a: (w / n if n else float("nan")) for a, (w, n) in tot.items()}
                table.append((rate["pith_skill"] - rate["english"], kind, name, rate))
        for diff, kind, name, rate in sorted(table):
            out.append(f"| {kind} | {name} | {f(rate['english'], 0)}% | {f(rate['terse'], 0)}% | "
                       f"{f(rate['pith_skill'], 0)}% | {diff * 100:+.0f} |")

    out += ["", "## Reading these numbers", "",
            "- **Message tokens** count only what the sender wrote. The Pith-with-skill arm also "
            "carries the skill text (about 2,500 tokens) in each agent's system prompt; the per-model "
            "`summary_h1.md` files report total tokens including it. With prompt caching that cost is "
            "paid once per conversation, not per message.",
            "- **Evidence-status diff** is the change in how often the reader correctly knew whether a "
            "claim was verified or only believed. This is the accuracy gain Pith is designed for.",
            "- **Intervals** are bootstrap over cases. With 60 cases, differences under about 10 points "
            "are within noise.",
            "- Results are for 4-bit quantized local models with greedy decoding. Larger or hosted "
            "models may behave differently.",
            "- Per-model details, with every transcript: `bench/results/handoff/<model>/`."]
    text = "\n".join(out) + "\n"
    with open(os.path.join(ROOT, "bench", "MODEL_RESULTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
